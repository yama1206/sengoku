// 2.10.0 湖・池・沼（大きいものと有名なもの）。地図に水色で出し、名前を書く。
// 【足すには】 LAKES に { name, pts:[[緯度,経度],…], big:true/false } を1つ足すだけ（big:true は引いた地図でも名前が出る）
// 街道や町をまたがない湖は、海と同じく「通れない水」になる（block は下で自動判定）。またぐものは絵だけで、歩いて渡れる。
(function () {
  const D = SGK.DATA, T = D.terrain, O = D.mapOrigin;
  const ll = ([lat, lon]) => [+((lon - O.lon) * 91).toFixed(2), +((O.lat - lat) * 111).toFixed(2)];
  // 楕円（円）の湖：中心の緯度経度・南北と東西の半径(km)
  const oval = (lat, lon, rn, re, n = 12) => Array.from({ length: n }, (_, i) => { const a = (i / n) * Math.PI * 2; return [lat + Math.sin(a) * rn / 111, lon + Math.cos(a) * re / 91]; });
  const LAKES = [
    { name: '霞ヶ浦', big: true, pts: [[36.20, 140.28], [36.16, 140.38], [36.08, 140.43], [36.03, 140.46], [35.97, 140.50], [35.95, 140.58], [36.00, 140.60], [36.06, 140.55], [36.12, 140.52], [36.18, 140.45], [36.22, 140.36]] },
    { name: '北浦', pts: [[36.12, 140.55], [36.04, 140.58], [35.97, 140.62], [35.97, 140.66], [36.05, 140.62], [36.13, 140.58]] },
    { name: '印旛沼', pts: [[35.80, 140.20], [35.77, 140.25], [35.74, 140.24], [35.75, 140.20]] },
    { name: '浜名湖', big: true, pts: [[34.84, 137.52], [34.80, 137.60], [34.78, 137.67], [34.74, 137.70], [34.70, 137.65], [34.69, 137.58], [34.73, 137.57], [34.77, 137.55], [34.80, 137.50]] },
    { name: '諏訪湖', pts: [[36.07, 138.09], [36.065, 138.13], [36.03, 138.125], [36.035, 138.08]] },
    { name: '猪苗代湖', big: true, pts: [[37.52, 140.08], [37.50, 140.15], [37.46, 140.18], [37.42, 140.14], [37.42, 140.08], [37.46, 140.04]] },
    { name: '宍道湖', big: true, pts: [[35.50, 132.93], [35.49, 133.02], [35.46, 133.09], [35.42, 133.06], [35.43, 132.97], [35.46, 132.91]] },
    { name: '中海', pts: [[35.55, 133.17], [35.52, 133.27], [35.46, 133.26], [35.46, 133.18]] },
    { name: '十和田湖', big: true, pts: [[40.52, 140.86], [40.52, 140.93], [40.47, 140.97], [40.42, 140.93], [40.43, 140.86], [40.47, 140.83]] },
    { name: '田沢湖', pts: oval(39.72, 140.66, 3, 3) },
    { name: '八郎潟', big: true, pts: [[40.02, 139.97], [40.00, 140.07], [39.90, 140.10], [39.85, 140.05], [39.88, 139.98], [39.95, 139.95]] },
    { name: '小川原湖', pts: [[40.78, 141.35], [40.78, 141.42], [40.72, 141.42], [40.68, 141.38], [40.70, 141.34]] },
    { name: '芦ノ湖', pts: [[35.22, 139.00], [35.21, 139.03], [35.17, 139.025], [35.18, 138.995]] },
    { name: '巨椋池', pts: [[34.92, 135.73], [34.92, 135.79], [34.88, 135.80], [34.87, 135.74]] },
    { name: '余呉湖', pts: oval(35.54, 136.20, 1, 1, 8) },
    { name: '湖山池', pts: oval(35.50, 134.17, 2, 2.5, 10) },
  ];
  // 琵琶湖はもう地形データ（seas）にあるので、名前だけ足す
  T.lakeLabels = [{ name: '琵琶湖', big: true, c: ll([35.27, 136.08]) }];
  T.lakes = LAKES.map((k) => { const pts = k.pts.map(ll); return { name: k.name, big: !!k.big, pts, c: [pts.reduce((s, q) => s + q[0], 0) / pts.length, pts.reduce((s, q) => s + q[1], 0) / pts.length] }; });
  // 町や街道をまたがない湖だけ、海と同じ「通れない水」にする
  const inPoly = (x, y, p) => { let c = false; for (let a = 0, b = p.length - 1; a < p.length; b = a++) { const [xa, ya] = p[a], [xb, yb] = p[b]; if ((ya > y) !== (yb > y) && x < ((xb - xa) * (y - ya)) / (yb - ya) + xa) c = !c; } return c; };
  const segHit = (p, ax, ay, bx, by) => { for (let t = 0; t <= 1.001; t += 0.05) if (inPoly(ax + (bx - ax) * t, ay + (by - ay) * t, p)) return true; return false; };
  for (const k of T.lakes) {
    const near = (D.settlements || []).some((s) => inPoly(s.x, s.y, k.pts)) || (T.roads || []).some((r) => r.pts.some((q, i) => i && segHit(k.pts, r.pts[i - 1][0], r.pts[i - 1][1], q[0], q[1])));
    k.block = !near; if (k.block) T.seas.push(k.pts);
  }
})();
